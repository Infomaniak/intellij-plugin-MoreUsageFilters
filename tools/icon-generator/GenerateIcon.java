import java.awt.Font;
import java.awt.RenderingHints;
import java.awt.font.FontRenderContext;
import java.awt.font.GlyphVector;
import java.awt.geom.AffineTransform;
import java.awt.geom.PathIterator;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/**
 * Generates a 16x16 toolbar icon from a short string, in the style of the platform's text icons, such as the serif "i"
 * of Show Import Statements: the text is set in JetBrains Mono Medium, the editor typeface, with a 9px cap height.
 *
 * <pre>
 * java tools/icon-generator/GenerateIcon.java "@P"                                         # light SVG on stdout
 * java tools/icon-generator/GenerateIcon.java "@P" src/main/resources/icons/showPreviewUsages  # writes .svg and _dark.svg
 * </pre>
 *
 * Run it from the root of the repository. Only a JDK is needed, no build step.
 */
public class GenerateIcon {

    private static final Path FONT = Path.of("tools/icon-generator/JetBrainsMono-Medium.ttf");
    private static final int CANVAS = 16;
    private static final double CAP_HEIGHT = 9.0;
    private static final double BASELINE = 11.0;
    private static final String LIGHT = "#6C707E";
    private static final String DARK = "#CED0D6";

    public static void main(String[] args) throws Exception {
        if (args.length < 1 || args.length > 2) {
            System.err.println("Usage: java tools/icon-generator/GenerateIcon.java <text> [output path without .svg]");
            System.exit(2);
        }
        String text = args[0];

        if (!Files.exists(FONT)) fail(FONT + " not found, run the command from the root of the repository.");

        String path = outline(text);

        if (args.length == 1) {
            System.out.print(svg(text, path, LIGHT));
        } else {
            Path light = Path.of(args[1] + ".svg");
            Path dark = Path.of(args[1] + "_dark.svg");
            Files.writeString(light, svg(text, path, LIGHT));
            Files.writeString(dark, svg(text, path, DARK));
            System.out.println("Wrote " + light + " and " + dark);
        }
    }

    private static String outline(String text) throws Exception {
        Font unit = Font.createFont(Font.TRUETYPE_FONT, FONT.toFile()).deriveFont(1000f);
        FontRenderContext frc = new FontRenderContext(
            null,
            RenderingHints.VALUE_TEXT_ANTIALIAS_ON,
            RenderingHints.VALUE_FRACTIONALMETRICS_ON
        );

        double capHeightAt1000 = unit.createGlyphVector(frc, "H").getOutline().getBounds2D().getHeight();
        Font font = unit.deriveFont((float) (1000 * CAP_HEIGHT / capHeightAt1000));

        GlyphVector glyphs = font.createGlyphVector(frc, text);
        double width = glyphs.getLogicalBounds().getWidth();
        if (width > CANVAS) {
            fail(String.format(Locale.ROOT, "\"%s\" is %.2fpx wide and does not fit in %dpx, use at most 2 characters.",
                text, width, CANVAS));
        }

        // Centred, snapped to half a pixel.
        double x = Math.round((CANVAS - width) / 2 * 2) / 2.0;
        PathIterator it = glyphs.getOutline((float) x, (float) BASELINE).getPathIterator(new AffineTransform());

        StringBuilder d = new StringBuilder();
        double[] c = new double[6];
        while (!it.isDone()) {
            switch (it.currentSegment(c)) {
                case PathIterator.SEG_MOVETO -> d.append('M').append(points(c, 1));
                case PathIterator.SEG_LINETO -> d.append('L').append(points(c, 1));
                case PathIterator.SEG_QUADTO -> d.append('Q').append(points(c, 2));
                case PathIterator.SEG_CUBICTO -> d.append('C').append(points(c, 3));
                case PathIterator.SEG_CLOSE -> d.append('Z');
            }
            it.next();
        }
        return d.toString();
    }

    private static String points(double[] c, int count) {
        StringBuilder s = new StringBuilder();
        for (int i = 0; i < count * 2; i++) {
            if (i > 0) s.append(' ');
            s.append(String.format(Locale.ROOT, "%.2f", c[i]));
        }
        return s.toString();
    }

    private static String svg(String text, String path, String color) {
        return """
            <!-- "%s" set in JetBrains Mono Medium (SIL Open Font License 1.1), the typeface the IDE uses in the editor.
                 Generated by tools/icon-generator/GenerateIcon.java, cap height 9px on a 16x16 canvas. -->
            <svg width="16" height="16" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg">
              <path d="%s" fill="%s"/>
            </svg>
            """.formatted(text.replace("--", "- -"), path, color);
    }

    private static void fail(String message) {
        System.err.println(message);
        System.exit(1);
    }
}
