import java.awt.Font
import java.awt.RenderingHints
import java.awt.font.FontRenderContext
import java.awt.geom.PathIterator
import java.nio.file.Files
import java.nio.file.Path
import java.util.Locale
import kotlin.math.roundToInt
import kotlin.system.exitProcess

/**
 * Generates a 16x16 toolbar icon from a short string, in the style of the platform's text icons, such as the serif "i"
 * of Show Import Statements: the text is set in JetBrains Mono Medium, the editor typeface, with a 9px cap height.
 *
 * ```
 * ./gradlew -q generateIcon --args='@P'                                          # light SVG on stdout
 * ./gradlew -q generateIcon --args='@P src/main/resources/icons/showPreviewUsages' # writes .svg and _dark.svg
 * ```
 */

private val FONT: Path = Path.of("tools/icon-generator/JetBrainsMono-Medium.ttf")
private const val CANVAS = 16
private const val CAP_HEIGHT = 9.0
private const val BASELINE = 11.0
private const val LIGHT = "#6C707E"
private const val DARK = "#CED0D6"

fun main(args: Array<String>) {
    if (args.size !in 1..2) fail("Usage: ./gradlew -q generateIcon --args='<text> [output path without .svg]'", 2)
    if (!Files.exists(FONT)) fail("$FONT not found, run the command from the root of the repository.")

    val text = args[0]
    val path = outline(text)

    if (args.size == 1) {
        print(svg(text, path, LIGHT))
    } else {
        val light = Path.of("${args[1]}.svg")
        val dark = Path.of("${args[1]}_dark.svg")
        Files.writeString(light, svg(text, path, LIGHT))
        Files.writeString(dark, svg(text, path, DARK))
        println("Wrote $light and $dark")
    }
}

private fun outline(text: String): String {
    val unit = Font.createFont(Font.TRUETYPE_FONT, FONT.toFile()).deriveFont(1000f)
    val frc = FontRenderContext(
        null,
        RenderingHints.VALUE_TEXT_ANTIALIAS_ON,
        RenderingHints.VALUE_FRACTIONALMETRICS_ON,
    )

    val capHeightAt1000 = unit.createGlyphVector(frc, "H").outline.bounds2D.height
    val font = unit.deriveFont((1000 * CAP_HEIGHT / capHeightAt1000).toFloat())

    val glyphs = font.createGlyphVector(frc, text)
    val width = glyphs.logicalBounds.width
    if (width > CANVAS) {
        fail("\"$text\" is ${"%.2f".format(Locale.ROOT, width)}px wide and does not fit in ${CANVAS}px, use at most 2 characters.")
    }

    // Centred, snapped to half a pixel.
    val x = ((CANVAS - width) / 2 * 2).roundToInt() / 2.0
    val iterator = glyphs.getOutline(x.toFloat(), BASELINE.toFloat()).getPathIterator(null)

    return buildString {
        val coords = DoubleArray(6)
        while (!iterator.isDone) {
            when (iterator.currentSegment(coords)) {
                PathIterator.SEG_MOVETO -> append('M').append(points(coords, 1))
                PathIterator.SEG_LINETO -> append('L').append(points(coords, 1))
                PathIterator.SEG_QUADTO -> append('Q').append(points(coords, 2))
                PathIterator.SEG_CUBICTO -> append('C').append(points(coords, 3))
                PathIterator.SEG_CLOSE -> append('Z')
            }
            iterator.next()
        }
    }
}

private fun points(coords: DoubleArray, count: Int): String =
    coords.take(count * 2).joinToString(" ") { "%.2f".format(Locale.ROOT, it) }

private fun svg(text: String, path: String, color: String): String = """
    |<!-- "${text.replace("--", "- -")}" set in JetBrains Mono Medium (SIL Open Font License 1.1), the typeface the IDE uses in the editor.
    |     Generated by tools/icon-generator/src/GenerateIcon.kt, cap height 9px on a 16x16 canvas. -->
    |<svg width="16" height="16" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg">
    |  <path d="$path" fill="$color"/>
    |</svg>
    |""".trimMargin()

private fun fail(message: String, status: Int = 1): Nothing {
    System.err.println(message)
    exitProcess(status)
}
